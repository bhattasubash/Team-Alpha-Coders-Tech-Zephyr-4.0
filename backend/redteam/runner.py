"""Red-team test runner. Loads prompt injection cases, runs them, writes report.

Currently a stub that loads and counts the cases. Will run actual LLM tests
once the AI provider is integrated.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

CASES_DIR = Path(__file__).parent / "cases"
REPORT_PATH = Path(__file__).resolve().parents[1].parent / "docs" / "redteam-report.md"


def load_cases() -> list[dict]:
    """Load all JSON test case files from the cases directory."""
    cases = []
    for f in sorted(CASES_DIR.glob("*.json")):
        with open(f, encoding="utf-8") as fh:
            case = json.load(fh)
            case["file"] = f.name
            cases.append(case)
    return cases


def run_cases(cases: list[dict]) -> dict:
    """Run each case through the AI layer and check the result.

    Returns summary stats. Currently a stub: no AI layer to test yet.
    """
    results = {
        "total": len(cases),
        "passed": 0,
        "failed": 0,
        "skipped": len(cases),  # all skipped until AI layer exists
        "details": [],
    }
    for case in cases:
        results["details"].append({
            "file": case["file"],
            "category": case["category"],
            "expected": case["expected"],
            "result": "skipped",
            "reason": "AI layer not integrated yet",
        })
    return results


def write_report(results: dict) -> None:
    """Write the red-team report to docs/redteam-report.md."""
    lines = [
        "# Red-team report",
        "",
        "Generated by backend/redteam/runner.py.",
        "",
        f"Last run: stub run (AI layer not integrated)",
        f"Cases: {results['total']}",
        f"Passed: {results['passed']}",
        f"Failed: {results['failed']}",
        f"Skipped: {results['skipped']}",
        f"Pass rate: N/A (no cases executed yet)",
        "",
        "## Cases",
        "",
        "| File | Category | Expected | Result |",
        "|------|----------|----------|--------|",
    ]
    for d in results["details"]:
        lines.append(f"| {d['file']} | {d['category']} | {d['expected']} | {d['result']} |")
    lines.append("")

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Report written to {REPORT_PATH}")


def main() -> None:
    """Entry point for `python -m redteam.runner`."""
    cases = load_cases()
    print(f"Loaded {len(cases)} red-team cases from {CASES_DIR}")
    results = run_cases(cases)
    write_report(results)
    print(f"Results: {results['passed']} passed, {results['failed']} failed, {results['skipped']} skipped")


if __name__ == "__main__":
    main()
